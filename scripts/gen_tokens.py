#!/usr/bin/env python3
"""Generate the Freeband design tokens for iOS and the hub from design/tokens.json.

    python3 -I scripts/gen_tokens.py          # write both outputs
    python3 -I scripts/gen_tokens.py --check  # exit 1 if either output is stale

Outputs:
    ios/Freeband/UI/Design/Tokens.generated.swift  raw tables read by Tokens.swift,
                                                   Typography.swift and Motion.swift
    hub/src/views/tokens.ts                        CSS custom properties for light, dark,
                                                   prefers-contrast: more and reduced motion

Standard library only. The JSON wins: never edit the outputs by hand.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "tokens.json"
SWIFT_OUT = ROOT / "ios" / "Freeband" / "UI" / "Design" / "Tokens.generated.swift"
TS_OUT = ROOT / "hub" / "src" / "views" / "tokens.ts"

HEADER = "Generated by scripts/gen_tokens.py from design/tokens.json. Do not edit; run `python3 -I scripts/gen_tokens.py`."
HEX = re.compile(r"^#[0-9A-F]{6}$")
VARIANTS = ("light", "dark", "lightContrast", "darkContrast")
TEXT_STYLES = {"largeTitle", "title", "title2", "title3", "headline", "body", "callout", "subheadline", "footnote", "caption", "caption2"}


class TokenError(ValueError):
    pass


def kebab(name: str) -> str:
    """camelCase -> kebab-case: textSecondary -> text-secondary, figureXL -> figure-xl, zone1 -> zone-1."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])|(?<=[A-Za-z])(?=[0-9])", "-", name).lower()


def number(value: float) -> str:
    """Shortest exact spelling: 4 -> "4", 1.5 -> "1.5", 0.33 -> "0.33"."""
    if float(value).is_integer():
        return str(int(value))
    return repr(float(value))


def resolve_colors(raw: dict) -> dict[str, dict[str, str]]:
    """Every colour as {light, dark, lightContrast, darkContrast}, aliases followed, hex upper-cased."""
    resolved: dict[str, dict[str, str]] = {}

    def resolve(name: str, trail: tuple[str, ...]) -> dict[str, str]:
        if name in resolved:
            return resolved[name]
        if name not in raw:
            raise TokenError(f"colour {trail[-1]!r} refers to unknown colour {name!r}")
        if name in trail:
            raise TokenError("colour alias cycle: " + " -> ".join(trail + (name,)))
        entry = raw[name]
        if "ref" in entry:
            values = dict(resolve(entry["ref"], trail + (name,)))
        else:
            values = {}
            for key in ("light", "dark"):
                if key not in entry:
                    raise TokenError(f"colour {name!r} has no {key!r} value")
                values[key] = entry[key].upper()
            values["lightContrast"] = entry.get("lightContrast", entry["light"]).upper()
            values["darkContrast"] = entry.get("darkContrast", entry["dark"]).upper()
        for key, value in values.items():
            if not HEX.match(value):
                raise TokenError(f"colour {name}.{key} = {value!r} is not #RRGGBB")
        resolved[name] = values
        return values

    for name in raw:
        if not re.match(r"^[a-z][A-Za-z0-9]*$", name):
            raise TokenError(f"colour name {name!r} must be camelCase")
        resolve(name, ())
    return {name: resolved[name] for name in raw}


def load(path: Path = SOURCE) -> dict:
    tokens = json.loads(path.read_text(encoding="utf-8"))
    tokens["_colors"] = resolve_colors(tokens["color"])
    for name, style in tokens["type"].items():
        if style["weight"] not in (400, 500):
            raise TokenError(f"type {name!r}: only weights 400 and 500 are allowed (600 is the Bold Text mapping)")
        if style["relativeTo"] not in TEXT_STYLES:
            raise TokenError(f"type {name!r}: unknown relativeTo {style['relativeTo']!r}")
    for name, motion in tokens["motion"].items():
        if len(motion["curve"]) != 4:
            raise TokenError(f"motion {name!r}: curve needs four control values")
    return tokens


# MARK: Swift

def swift_hex(value: str) -> str:
    return "0x" + value[1:]


def swift(tokens: dict) -> str:
    colors = tokens["_colors"]
    out: list[str] = [
        f"// {HEADER}",
        "// swiftlint:disable all",
        "import CoreGraphics",
        "import SwiftUI",
        "",
        "/// Raw design-token tables. Views use the semantic API in Tokens.swift, Typography.swift and Motion.swift.",
        "enum FBTokenTable {",
        "    struct ColorEntry: Hashable, Sendable {",
        "        let name: String",
        "        let light: UInt32",
        "        let dark: UInt32",
        "        let lightContrast: UInt32",
        "        let darkContrast: UInt32",
        "    }",
        "",
        "    struct TypeEntry: Sendable {",
        "        let name: String",
        "        let size: CGFloat",
        "        let lineHeight: CGFloat",
        "        /// 400 or 500; Bold Text maps them to 500 and 600.",
        "        let weight: Int",
        "        let relativeTo: Font.TextStyle",
        "        let isFigure: Bool",
        "    }",
        "",
        "    struct MotionEntry: Sendable {",
        "        let c0x: Double",
        "        let c0y: Double",
        "        let c1x: Double",
        "        let c1y: Double",
        "        let duration: Double",
        "    }",
        "",
        "    enum Colors {",
    ]
    for name, v in colors.items():
        out.append(
            f"        static let {name} = ColorEntry(name: \"{name}\", light: {swift_hex(v['light'])}, dark: {swift_hex(v['dark'])}, "
            f"lightContrast: {swift_hex(v['lightContrast'])}, darkContrast: {swift_hex(v['darkContrast'])})"
        )
    out.append("")
    out.append("        static let all: [ColorEntry] = [")
    out.extend(f"            {name}," for name in colors)
    out.append("        ]")
    out.append("    }")

    for group, enum in (("space", "Space"), ("radius", "Radius"), ("stroke", "Stroke"), ("size", "Size")):
        out.append("")
        out.append(f"    enum {enum} {{")
        for name, value in tokens[group].items():
            out.append(f"        static let {name}: CGFloat = {number(value)}")
        out.append("")
        out.append("        static let all: [(name: String, value: CGFloat)] = [")
        out.extend(f"            (\"{name}\", {name})," for name in tokens[group])
        out.append("        ]")
        out.append("    }")

    out.append("")
    out.append("    enum TypeScale {")
    for name, s in tokens["type"].items():
        out.append(
            f"        static let {name} = TypeEntry(name: \"{name}\", size: {number(s['size'])}, lineHeight: {number(s['lineHeight'])}, "
            f"weight: {s['weight']}, relativeTo: .{s['relativeTo']}, isFigure: {'true' if s['figure'] else 'false'})"
        )
    out.append("    }")

    font = tokens["font"]
    out.append("")
    out.append("    enum FontName {")
    out.append(f"        static let family = \"{font['family']}\"")
    out.append(f"        static let regular = \"{font['regular']}\"")
    out.append(f"        static let medium = \"{font['medium']}\"")
    out.append(f"        static let semibold = \"{font['semibold']}\"")
    out.append("    }")

    out.append("")
    out.append("    enum Motion {")
    for name, m in tokens["motion"].items():
        c = [number(x) for x in m["curve"]]
        out.append(f"        static let {name} = MotionEntry(c0x: {c[0]}, c0y: {c[1]}, c1x: {c[2]}, c1y: {c[3]}, duration: {number(m['duration'])})")
    out.append("    }")

    out.append("")
    out.append("    enum Bands {")
    for score, limits in tokens["bands"].items():
        out.append(f"        enum {score[0].upper() + score[1:]} {{")
        for key, value in limits.items():
            out.append(f"            static let {key}: Double = {number(value)}")
        out.append("        }")
    out.append("    }")
    out.append("}")
    out.append("")
    return "\n".join(out)


# MARK: TypeScript / CSS

def color_vars(tokens: dict) -> dict[str, dict[str, str]]:
    colors = tokens["_colors"]
    light = {f"--{kebab(n)}": v["light"] for n, v in colors.items()}
    dark = {f"--{kebab(n)}": v["dark"] for n, v in colors.items()}
    # A contrast block carries every colour that changes in either theme, so the dark contrast
    # block always overrides whatever the light contrast block set.
    changed = [n for n, v in colors.items() if v["lightContrast"] != v["light"] or v["darkContrast"] != v["dark"]]
    light_c = {f"--{kebab(n)}": colors[n]["lightContrast"] for n in changed}
    dark_c = {f"--{kebab(n)}": colors[n]["darkContrast"] for n in changed}
    return {"light": light, "dark": dark, "lightContrast": light_c, "darkContrast": dark_c}


def static_vars(tokens: dict) -> dict[str, str]:
    font = tokens["font"]
    out: dict[str, str] = {}
    for group in ("space", "radius", "stroke", "size"):
        for name, value in tokens[group].items():
            out[f"--{group}-{kebab(name)}"] = f"{number(value)}px"
    out["--font-sans"] = f"\"{font['family']}\", {font['fallback']}"
    for name, s in tokens["type"].items():
        key = kebab(name)
        out[f"--type-{key}"] = f"{s['weight']} {number(s['size'])}px/{number(s['lineHeight'])}px var(--font-sans)"
        out[f"--type-{key}-numeric"] = "tabular-nums" if s["figure"] else "normal"
    for name, m in tokens["motion"].items():
        key = kebab(name)
        out[f"--ease-{key}"] = "cubic-bezier(" + ",".join(number(x) for x in m["curve"]) + ")"
        out[f"--duration-{key}"] = f"{round(m['duration'] * 1000)}ms"
    return out


def reduced_motion_vars(tokens: dict) -> dict[str, str]:
    # Colour fades stay (they are not motion); the arc reveal is drawn at once.
    return {f"--duration-{kebab(name)}": "0ms" for name in tokens["motion"] if name != "standard"}


def block(selector: str, decls: dict[str, str]) -> str:
    return selector + "{" + ";".join(f"{k}:{v}" for k, v in decls.items()) + "}"


def css(tokens: dict) -> str:
    c = color_vars(tokens)
    parts = [
        block(":root", {"color-scheme": "light dark", **c["light"], **static_vars(tokens)}),
        "@media (prefers-color-scheme:dark){" + block(":root", c["dark"]) + "}",
        "@media (prefers-contrast:more){" + block(":root", c["lightContrast"]) + "}",
        "@media (prefers-color-scheme:dark) and (prefers-contrast:more){" + block(":root", c["darkContrast"]) + "}",
        "@media (prefers-reduced-motion:reduce){" + block(":root", reduced_motion_vars(tokens)) + "}",
    ]
    return "\n".join(parts)


def ts_object(d: dict, indent: int = 2) -> str:
    pad = " " * indent
    lines = ["{"]
    for k, v in d.items():
        if isinstance(v, dict):
            lines.append(f"{pad}{json.dumps(k)}: {ts_object(v, indent + 2)},")
        else:
            lines.append(f"{pad}{json.dumps(k)}: {json.dumps(v)},")
    lines.append(" " * (indent - 2) + "}")
    return "\n".join(lines)


def typescript(tokens: dict) -> str:
    bands = {score: dict(limits) for score, limits in tokens["bands"].items()}
    out = [
        f"// {HEADER}",
        "// Freeband v3 tokens as CSS custom properties: light by default, dark under",
        "// prefers-color-scheme, Increase Contrast under prefers-contrast: more.",
        "",
        f"export const TOKENS_VERSION = {tokens['version']};",
        "",
        f"export const COLOR_VARS = {ts_object(color_vars(tokens))} as const;",
        "",
        f"export const STATIC_VARS = {ts_object(static_vars(tokens))} as const;",
        "",
        f"export const REDUCED_MOTION_VARS = {ts_object(reduced_motion_vars(tokens))} as const;",
        "",
        f"export const BANDS = {ts_object(bands)} as const;",
        "",
        f"export const TOKEN_CSS = {json.dumps(css(tokens))};",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    try:
        tokens = load()
    except (TokenError, KeyError, json.JSONDecodeError) as error:
        print(f"gen_tokens: {error}", file=sys.stderr)
        return 2
    outputs = {SWIFT_OUT: swift(tokens), TS_OUT: typescript(tokens)}
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    for path in stale:
        verb = "stale" if check else "wrote"
        print(f"{verb} {path.relative_to(ROOT)}")
    if check and stale:
        print("gen_tokens: outputs are out of date; run python3 -I scripts/gen_tokens.py", file=sys.stderr)
        return 1
    if not stale:
        print("tokens up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
